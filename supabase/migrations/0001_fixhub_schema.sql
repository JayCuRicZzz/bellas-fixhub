-- ============================================================
-- Bellas FixHub — Supabase (Postgres) schema
-- Schema: fixhub  (shared project "bella-hr", isolated schema)
-- Auth:   Supabase Auth (auth.users) → fixhub.profiles
-- ============================================================

create schema if not exists fixhub;

-- ---------- helpers ----------
create or replace function fixhub.today_bkk() returns date
language sql stable as $$ select (now() at time zone 'Asia/Bangkok')::date $$;

create or replace function fixhub.set_updated_at() returns trigger
language plpgsql as $$
begin new.updated_at = now(); return new; end $$;

-- ---------- reference tables ----------
create table if not exists fixhub.branches (
  branch_code   text primary key,
  branch_name   text not null,
  branch_name_en text not null,
  sort_order    int not null default 0,
  active        boolean not null default true
);

create table if not exists fixhub.categories (
  category_id  int generated by default as identity primary key,
  dept_type    text not null check (dept_type in ('MAINTENANCE','IT')),
  main_th      text not null,
  main_en      text not null default '',
  sub_th       text not null default '',
  sub_en       text not null default '',
  active       boolean not null default true
);

create table if not exists fixhub.sla_config (
  priority     text primary key check (priority in ('non_urgent','low','medium','high','urgent')),
  sla_minutes  int not null,
  description  text
);

-- ---------- users (profiles over Supabase Auth) ----------
create table if not exists fixhub.profiles (
  user_id      uuid primary key references auth.users(id) on delete cascade,
  username     text not null unique,
  full_name    text not null,
  role         text not null check (role in ('admin','gm','sup','supit','tech','it','front','house')),
  department   text,
  branch_code  text references fixhub.branches(branch_code),
  password_reset_required boolean not null default false,
  active       boolean not null default true,
  created_at   timestamptz not null default now(),
  updated_at   timestamptz not null default now()
);
create trigger trg_profiles_updated before update on fixhub.profiles
  for each row execute function fixhub.set_updated_at();

create table if not exists fixhub.user_branches (
  user_id      uuid not null references fixhub.profiles(user_id) on delete cascade,
  branch_code  text not null references fixhub.branches(branch_code),
  primary key (user_id, branch_code)
);

-- ---------- tickets ----------
create table if not exists fixhub.tickets (
  ticket_id     int generated by default as identity primary key,
  ticket_number text not null unique,
  branch_code   text not null references fixhub.branches(branch_code),
  category_id   int not null references fixhub.categories(category_id),
  reporter_id   uuid references fixhub.profiles(user_id) on delete set null,
  reporter_department text,                       -- MAINT / IT (department that owns the work)
  technician_id uuid references fixhub.profiles(user_id) on delete set null,
  accepted_by   uuid references fixhub.profiles(user_id) on delete set null,
  resolved_by   uuid references fixhub.profiles(user_id) on delete set null,
  approved_by   uuid references fixhub.profiles(user_id) on delete set null,
  location_detail text not null,
  description   text not null,
  priority      text not null default 'medium' check (priority in ('non_urgent','low','medium','high','urgent')),
  difficulty    text default 'medium' check (difficulty in ('easy','medium','hard','very_hard')),
  status        text not null default 'PENDING'
                check (status in ('PENDING','ACCEPTED','IN_PROGRESS','PAUSED','RESOLVED','APPROVED','REJECTED','FLAGGED','CANCELLED')),
  pending_reason text,
  paused_reason text,
  paused_at     timestamptz,
  paused_expected_end timestamptz,
  kpi_rating    smallint check (kpi_rating between 1 and 5),
  sla_deadline  timestamptz,
  sla_minutes   int,                              -- actual minutes accepted→resolved
  accepted_at   timestamptz,
  resolved_at   timestamptz,
  approved_at   timestamptz,
  created_at    timestamptz not null default now(),
  updated_at    timestamptz not null default now()
);
create index if not exists idx_tickets_branch   on fixhub.tickets(branch_code);
create index if not exists idx_tickets_status   on fixhub.tickets(status);
create index if not exists idx_tickets_created  on fixhub.tickets(created_at desc);
create index if not exists idx_tickets_tech     on fixhub.tickets(technician_id);
create index if not exists idx_tickets_reporter on fixhub.tickets(reporter_id);
create index if not exists idx_tickets_dept     on fixhub.tickets(reporter_department);
create trigger trg_tickets_updated before update on fixhub.tickets
  for each row execute function fixhub.set_updated_at();

-- atomic ticket numbering: {BRANCH}-{EN|IT}-{YYYY}-{MM}-{00001}
create table if not exists fixhub.ticket_counters (
  prefix text primary key,
  seq    int not null default 0
);
create or replace function fixhub.next_ticket_number(p_branch text, p_dept_code text)
returns text language plpgsql as $$
declare
  v_prefix text := p_branch || '-' || p_dept_code || '-' || to_char(now() at time zone 'Asia/Bangkok', 'YYYY-MM') || '-';
  v_seq int;
begin
  insert into fixhub.ticket_counters(prefix, seq) values (v_prefix, 1)
  on conflict (prefix) do update set seq = fixhub.ticket_counters.seq + 1
  returning seq into v_seq;
  return v_prefix || lpad(v_seq::text, 5, '0');
end $$;

create table if not exists fixhub.ticket_images (
  image_id     int generated by default as identity primary key,
  ticket_id    int not null references fixhub.tickets(ticket_id) on delete cascade,
  image_url    text not null,
  storage_path text,
  image_type   text not null default 'report' check (image_type in ('report','repair','other')),
  uploaded_by  uuid references fixhub.profiles(user_id) on delete set null,
  uploaded_at  timestamptz not null default now()
);
create index if not exists idx_ticket_images_ticket on fixhub.ticket_images(ticket_id);

create table if not exists fixhub.ticket_activity_log (
  id            bigint generated by default as identity primary key,
  ticket_id     int not null references fixhub.tickets(ticket_id) on delete cascade,
  action        text not null,
  old_status    text,
  new_status    text,
  action_by     uuid references fixhub.profiles(user_id) on delete set null,
  action_by_name text,
  reason        text,
  created_at    timestamptz not null default now()
);
create index if not exists idx_log_ticket on fixhub.ticket_activity_log(ticket_id, created_at desc);

-- ---------- preventive maintenance ----------
create table if not exists fixhub.pm_schedules (
  id              int generated by default as identity primary key,
  branch_code     text not null references fixhub.branches(branch_code),
  title           text not null,
  description     text not null default '',
  department      text not null default 'MAINT',
  category_id     int not null references fixhub.categories(category_id),
  frequency_value int not null check (frequency_value > 0),
  frequency_unit  text not null default 'month' check (frequency_unit in ('day','week','month','year')),
  last_run        timestamptz,
  next_run        timestamptz not null,
  created_by      uuid references fixhub.profiles(user_id) on delete set null,
  active          boolean not null default true,
  created_at      timestamptz not null default now()
);
create index if not exists idx_pm_next_run on fixhub.pm_schedules(next_run) where active;

create table if not exists fixhub.pm_logs (
  id         bigint generated by default as identity primary key,
  pm_id      int not null references fixhub.pm_schedules(id) on delete cascade,
  ticket_id  int references fixhub.tickets(ticket_id) on delete set null,
  run_at     timestamptz not null default now()
);

-- ---------- app settings (LINE config etc.) ----------
create table if not exists fixhub.app_settings (
  key        text primary key,
  value      jsonb not null default '{}'::jsonb,
  updated_by uuid,
  updated_at timestamptz not null default now()
);

-- ---------- view: tickets with joined names ----------
create or replace view fixhub.tickets_full as
select t.*,
       c.main_th, c.main_en, c.sub_th, c.sub_en, c.dept_type,
       r.full_name  as reporter_name,
       tu.full_name as technician_name,
       au.full_name as accepted_by_name,
       ru.full_name as resolved_by_name,
       apu.full_name as approved_by_name,
       (t.sla_deadline is not null and t.status not in ('APPROVED','CANCELLED') and now() > t.sla_deadline) as sla_overdue
from fixhub.tickets t
join fixhub.categories c on c.category_id = t.category_id
left join fixhub.profiles r   on r.user_id  = t.reporter_id
left join fixhub.profiles tu  on tu.user_id = t.technician_id
left join fixhub.profiles au  on au.user_id = t.accepted_by
left join fixhub.profiles ru  on ru.user_id = t.resolved_by
left join fixhub.profiles apu on apu.user_id = t.approved_by;

